function audienceLabel(audience) {
  if (!isEnglish || !audience) return audience;
  const [, year, category] = audience.match(/^(\d{4})届?(.*)$/) || ["", "", audience];
  const audienceNames = {
    "": "",
    "本科生": "Undergraduates",
    "本科毕业生": "Undergraduate graduates",
    "研究生": "Graduate students",
    "毕业生": "Graduates",
    "毕业生（含本科生、研究生）": "Undergraduate and graduate students",
    "本科和研究生同学": "Undergraduate and graduate students",
    "研究生及返校往届毕业生": "Graduate students and returning alumni",
    "毕业生（本科、研究生典礼同题讲话）": "Graduates (same topic at the undergraduate and graduate ceremonies)",
  };
  const label = audienceNames[category];
  if (label === undefined) return audience;
  return [year ? t("cohortOption", year) : "", label].filter(Boolean).join(" · ");
}

function t(key, ...values) {
  return messages[key][isEnglish ? 1 : 0].replace(/\{(\d+)\}/g, (_, index) => values[index]);
}

function codeLabel(key) {
  return (isEnglish ? englishCodeLabels[key] : undefined) || catalog.codes[key] || catalog.moves[key];
}

function metadataLabel(value) {
  return (isEnglish ? englishMetadataLabels[value] : undefined) || value;
}
